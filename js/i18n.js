const I18N={id:{},en:{}};
TX.forEach(([k,a,b])=>{I18N.id[k]=a;I18N.en[k]=b});
let lang='id';
try{
  const sv=localStorage.getItem('blox-lang');
  lang=(sv==='id'||sv==='en')?sv:((navigator.language||'id').toLowerCase().startsWith('id')?'id':'en');
}catch(e){}
function t(k,v){
  let s=I18N[lang][k];
  if(s===undefined)s=I18N.id[k];
  if(s===undefined)return k;
  if(v)s=s.replace(/\{(\w+)\}/g,(m,n)=>v[n]!==undefined?v[n]:m);
  return s;
}
const dateLoc=()=>lang==='id'?'id-ID':'en-US';
/* Terapkan terjemahan ke elemen statis: data-i18n (teks), data-i18n-ph (placeholder), data-i18n-aria (label aksesibilitas) */
function applyI18n(){
  document.documentElement.lang=lang;
  document.querySelectorAll('[data-i18n]').forEach(e=>{e.textContent=t(e.dataset.i18n)});
  document.querySelectorAll('[data-i18n-ph]').forEach(e=>{e.placeholder=t(e.dataset.i18nPh)});
  document.querySelectorAll('[data-i18n-aria]').forEach(e=>{e.setAttribute('aria-label',t(e.dataset.i18nAria))});
}
